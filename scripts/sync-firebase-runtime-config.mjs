/**
 * Writes public/firebase-runtime-config.js from .env FIREBASE_API_KEY.
 * Used by `ng serve` (SSR injection only runs on the Node production server).
 * Never overwrites a key already injected by SSR (production Cloud Run).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'public', 'firebase-runtime-config.js');

function readEnvKey() {
  if (process.env.FIREBASE_API_KEY?.trim()) {
    return process.env.FIREBASE_API_KEY.trim();
  }
  const envPath = join(root, '.env');
  if (!existsSync(envPath)) return '';
  const text = readFileSync(envPath, 'utf8');
  const match = text.match(/^\s*FIREBASE_API_KEY\s*=\s*(.+)\s*$/m);
  if (!match) return '';
  return match[1].trim().replace(/^['"]|['"]$/g, '');
}

const apiKey = readEnvKey();
const contents = `/* Generated by scripts/sync-firebase-runtime-config.mjs — do not edit */
(function () {
  if (typeof window === 'undefined') return;
  if (!window.__FIREBASE_API_KEY__) {
    window.__FIREBASE_API_KEY__ = ${JSON.stringify(apiKey)};
  }
})();
`;

writeFileSync(outFile, contents, 'utf8');
console.log(
  apiKey
    ? `firebase-runtime-config.js written (apiKey length=${apiKey.length})`
    : 'firebase-runtime-config.js written (empty apiKey — local auth fallback will be used)'
);
